namespace aes_detail {

static inline uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        bool hi = (a & 0x80);
        a <<= 1;
        if (hi) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

} // namespace aes_detail

class AES128 {
    uint8_t round_keys[11][16];

public:
    static const uint8_t SBOX[256];
    static const uint8_t INV_SBOX[256];
    static const uint8_t RCON[10];

private:
    void key_expansion(const uint8_t key[16]) {
        std::memcpy(round_keys[0], key, 16);
        for (int i = 1; i <= 10; i++) {
            const uint8_t* prev = round_keys[i-1];
            uint8_t*       cur  = round_keys[i];
            // First word: RotWord + SubWord + Rcon
            cur[0] = SBOX[prev[13]] ^ RCON[i-1] ^ prev[0];
            cur[1] = SBOX[prev[14]] ^ prev[1];
            cur[2] = SBOX[prev[15]] ^ prev[2];
            cur[3] = SBOX[prev[12]] ^ prev[3];
            // Words 1,2,3
            for (int j = 4; j < 16; j++) cur[j] = prev[j] ^ cur[j-4];
        }
    }

    void sub_bytes(uint8_t s[16]) const {
        for (int i = 0; i < 16; i++) s[i] = SBOX[s[i]];
    }

    void shift_rows(uint8_t s[16]) const {
        uint8_t t;
        // row 1 left by 1
        t = s[1]; s[1]=s[5]; s[5]=s[9]; s[9]=s[13]; s[13]=t;
        // row 2 left by 2
        t=s[2];  s[2]=s[10];  s[10]=t;
        t=s[6];  s[6]=s[14];  s[14]=t;
        // row 3 left by 3 (= right by 1)
        t=s[15]; s[15]=s[11]; s[11]=s[7]; s[7]=s[3]; s[3]=t;
    }

    void mix_columns(uint8_t s[16]) const {
        using aes_detail::gmul;
        for (int c = 0; c < 4; c++) {
            uint8_t* col = s + c*4;
            uint8_t a0=col[0], a1=col[1], a2=col[2], a3=col[3];
            col[0] = gmul(2,a0)^gmul(3,a1)^a2^a3;
            col[1] = a0^gmul(2,a1)^gmul(3,a2)^a3;
            col[2] = a0^a1^gmul(2,a2)^gmul(3,a3);
            col[3] = gmul(3,a0)^a1^a2^gmul(2,a3);
        }
    }

    void inv_sub_bytes(uint8_t s[16]) const {
        for (int i = 0; i < 16; i++) s[i] = INV_SBOX[s[i]];
    }

    void inv_shift_rows(uint8_t s[16]) const {
        uint8_t t;
        // row 1 right by 1
        t=s[13]; s[13]=s[9]; s[9]=s[5]; s[5]=s[1]; s[1]=t;
        // row 2 right by 2
        t=s[2];  s[2]=s[10];  s[10]=t;
        t=s[6];  s[6]=s[14];  s[14]=t;
        // row 3 right by 3 (= left by 1)
        t=s[3];  s[3]=s[7];   s[7]=s[11]; s[11]=s[15]; s[15]=t;
    }

    void inv_mix_columns(uint8_t s[16]) const {
        using aes_detail::gmul;
        for (int c = 0; c < 4; c++) {
            uint8_t* col = s + c*4;
            uint8_t a0=col[0], a1=col[1], a2=col[2], a3=col[3];
            col[0] = gmul(0x0e,a0)^gmul(0x0b,a1)^gmul(0x0d,a2)^gmul(0x09,a3);
            col[1] = gmul(0x09,a0)^gmul(0x0e,a1)^gmul(0x0b,a2)^gmul(0x0d,a3);
            col[2] = gmul(0x0d,a0)^gmul(0x09,a1)^gmul(0x0e,a2)^gmul(0x0b,a3);
            col[3] = gmul(0x0b,a0)^gmul(0x0d,a1)^gmul(0x09,a2)^gmul(0x0e,a3);
        }
    }

    void add_round_key(uint8_t s[16], int round) const {
        for (int i = 0; i < 16; i++) s[i] ^= round_keys[round][i];
    }

public:
    AES128() = default;
    AES128(const uint8_t key[16]) { key_expansion(key); }

    void encrypt(const uint8_t in[16], uint8_t out[16]) const {
        uint8_t s[16];
        std::memcpy(s, in, 16);
        add_round_key(s, 0);
        for (int r = 1; r <= 9; r++) {
            sub_bytes(s);
            shift_rows(s);
            mix_columns(s);
            add_round_key(s, r);
        }
        sub_bytes(s);
        shift_rows(s);
        add_round_key(s, 10);
        std::memcpy(out, s, 16);
    }

    void decrypt(const uint8_t in[16], uint8_t out[16]) const {
        uint8_t s[16];
        std::memcpy(s, in, 16);
        add_round_key(s, 10);
        for (int r = 9; r >= 1; r--) {
            inv_shift_rows(s);
            inv_sub_bytes(s);
            add_round_key(s, r);
            inv_mix_columns(s);
        }
        inv_shift_rows(s);
        inv_sub_bytes(s);
        add_round_key(s, 0);
        std::memcpy(out, s, 16);
    }
};

